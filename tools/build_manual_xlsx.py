def add_screenshot_sheet(wb):
    ws = wb.create_sheet("截图说明")
    put_head(ws, 1, ["序号", "关联用例", "截图说明", "图片文件", "截图预览"],
             [6, 12, 26, 34, 70])
    r = 2
    for idx, (case, desc, rel, note) in enumerate(SHOT_DESC, 1):
        ws.cell(row=r, column=1, value=idx).alignment = CENTER
        ws.cell(row=r, column=2, value=case).alignment = CENTER
        ws.cell(row=r, column=3, value=desc + "（" + note + "）").alignment = WRAP
        ws.cell(row=r, column=4, value=rel).alignment = WRAP
        path = os.path.join(SHOT, rel.replace("/", os.sep))
        if os.path.exists(path):
            im = PILImage.open(path)
            im.thumbnail((620, 400))
            tmp = os.path.join(ROOT, "target", "shot_%02d.png" % idx)
            os.makedirs(os.path.dirname(tmp), exist_ok=True)
            im.save(tmp)
            img = XLImage(tmp)
            ws.add_image(img, "E%d" % r)
            ws.row_dimensions[r].height = 210
        for c in range(1, 6):
            ws.cell(row=r, column=c).border = BORDER
        r += 1


